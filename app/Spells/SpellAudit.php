<?php

namespace App\Spells;

use App\Compendium\SrdSpellMapper;
use App\Models\CompendiumEntry;
use App\Services\CharacterGameplay;
use Illuminate\Support\Facades\Validator;

class SpellAudit
{
    public function run(): array
    {
        $rows = [];
        $counts = ['FULL' => 0, 'PARTIAL' => 0, 'MANUAL' => 0];
        $errors = [];
        foreach (CompendiumEntry::whereHas('source', fn ($q) => $q->where('key', 'srd-2024'))->where('entity_type', 'spells')->orderBy('external_key')->get() as $entry) {
            $n = array_replace($entry->normalized_data, app(SrdSpellMapper::class)->map($entry->raw_data));
            $n['source_key'] = $entry->external_key;
            $n['source_entry_id'] = $entry->id;
            $ability = app(SpellProjection::class)->ability($n, 0);
            $v = Validator::make(['abilities' => [$ability]], CharacterGameplay::rules());
            if ($v->fails()) {
                $errors[$entry->external_key] = $v->errors()->all();
            }
            $coverage = app(SpellProjection::class)->coverage($entry->external_key);
            $counts[$coverage['status']]++;
            $warnings = [];
            if (str_contains(strtolower($entry->raw_data['range'] ?? ''), 'component')) {
                $warnings[] = 'Components embedded in range; original retained, requires reviewed correction.';
            }
            if (empty($entry->raw_data['damage']['damage_at_character_level']) && $n['spell_level'] === 0 && isset($entry->raw_data['damage'])) {
                $warnings[] = 'Cantrip progression absent from structured damage; explicit tier/recipe required.';
            }
            $rows[] = ['key' => $entry->external_key, 'name' => $entry->name, 'level' => $n['spell_level'], ...$coverage, 'warnings' => $warnings, 'checksum' => $entry->checksum];
        }

        return ['total' => count($rows), 'counts' => $counts, 'errors' => $errors, 'spells' => $rows];
    }

    public function markdown(array $audit): string
    {
        $text = "# SRD spell coverage — Task 29\n\nLocal SRD 2024 Compendium; canonical SRD 5.2.1. Generated by `php artisan spells:audit`. No campaign copies are created.\n\n";
        foreach ($audit['counts'] as $status => $n) {
            $text .= "$status: **$n / {$audit['total']}**  \n";
        }
        $text .= "\nFULL means core mechanics within YTT's declared creature/2D tabletop model. Shared limits still apply: no class progression, automatic focus/hand/material-cost inference, cover/LOS/vertical volume engine or automatic reaction prompts. Cantrip tier is explicit GM configuration. PARTIAL applies only the listed recipe; remaining mechanics need GM. MANUAL casts never infer effects from prose; GM enables casting, handles the effect, and marks the persisted cast resolved. Long casts require explicit GM completion outside combat.\n\n";
        $categories = [];
        foreach ($audit['spells'] as $r) {
            if ($r['status'] !== 'FULL') {
                $categories[$r['category']] = ($categories[$r['category']] ?? 0) + 1;
            }
        }
        $text .= "## Remaining rule families\n\n| Family | Spells |\n|---|---:|\n";
        foreach ($categories as $k => $n) {
            $text .= "| $k | $n |\n";
        }
        $text .= "\n## Every imported spell\n\n| Key / spell | Level | Coverage | Reason / source issues |\n|---|---:|---|---|\n";
        foreach ($audit['spells'] as $r) {
            $text .= '| '.$r['key'].' · '.$r['name'].' | '.$r['level'].' | '.$r['status'].' | '.str_replace(["\n", '|'], [' ', '/'], $r['reason'].' '.implode(' ', $r['warnings']))." |\n";
        }
        $text .= "\n## Concrete blockers\n\nSelected multi-target lists, per-ray/dart allocation and repeated activations; repeat saves and exact conditional endings; creature types and special senses; persistent terrain/objects/lighting/aura entry; summoning and transformations; portals, elevation and safe teleport destinations; rest/death/revival states; special reaction interception; costly component/focus eligibility and missing structured cantrip/healing/scaling data. Original metadata and descriptions remain in Compendium and independent spell copies.\n\nSee [SPELLCASTING.md](SPELLCASTING.md) for execution, component/scroll rules, tests and local verification.\n";

        return $text;
    }
}
